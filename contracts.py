"""Provider contracts for authorized market-data and broker integrations.

No live provider is bundled. Implement these protocols in a provider-specific adapter
after obtaining the vendor/broker's credentials, entitlements and API documentation.
"""
from typing import Protocol, Iterable, Mapping, Any

class MarketDataAdapter(Protocol):
    provider_id: str
    def historical_bars(self, symbols: list[str], start_date: str, end_date: str) -> Iterable[Mapping[str, Any]]: ...
    def latest_quotes(self, symbols: list[str]) -> Mapping[str, Mapping[str, Any]]: ...

class BrokerAdapter(Protocol):
    broker_id: str
    def account_summary(self) -> Mapping[str, Any]: ...
    def positions(self) -> Iterable[Mapping[str, Any]]: ...
    def orders(self) -> Iterable[Mapping[str, Any]]: ...
    def submit_order(self, order: Mapping[str, Any]) -> Mapping[str, Any]: ...
